/** Переводит строку на выбранный язык; явный lang не меняет настройку интерфейса. */
export function t(s: string, values?: Record<string, string | number>, lang: Lang = useLangStore.getState().lang): string {
  const translated = lang === "ru" ? RU[s] ?? s : s;
  return translated.replace(/\{(\w+)\}/g, (placeholder, key: string) =>
    values && Object.prototype.hasOwnProperty.call(values, key) ? String(values[key]) : placeholder);
}

/** Format at render time so loaded timestamps follow a language change. */
export function formatRelativeTime(iso?: string | null): string {
  if (!iso) return "";
  const timestamp = Date.parse(iso);
  if (!Number.isFinite(timestamp)) return "";
  const seconds = Math.max(0, Math.floor((Date.now() - timestamp) / 1000));
  if (seconds < 60) return t("just now");
  const minutes = Math.floor(seconds / 60);
  const hours = Math.floor(minutes / 60);
  const days = Math.floor(hours / 24);
  const value = minutes < 60 ? minutes : hours < 24 ? hours : days < 30 ? days : Math.floor(days / 30);
  const unit = minutes < 60 ? "minute" : hours < 24 ? "hour" : days < 30 ? "day" : "month";
  if (useLangStore.getState().lang === "ru") {
    return new Intl.RelativeTimeFormat("ru", { numeric: "auto", style: "short" }).format(-value, unit);
  }
  return unit === "day" && value === 1 ? "Yesterday" : `${value} ${unit === "minute" ? "min" : unit === "hour" ? "h" : unit === "day" ? "days" : "mo"} ago`;
}

/** Russian count forms used by activity sentences; preserve technical names. */
export function activityNoun(singular: string, plural: string, count: number): string {
  if (useLangStore.getState().lang !== "ru") return count === 1 ? singular : plural;
  const forms: Record<string, [string, string, string]> = {
    finding: ["уязвимость", "уязвимости", "уязвимостей"],
    host: ["хост", "хоста", "хостов"],
    "IP address": ["IP-адрес", "IP-адреса", "IP-адресов"],
    service: ["сервис", "сервиса", "сервисов"],
    endpoint: ["эндпоинт", "эндпоинта", "эндпоинтов"],
    note: ["заметку", "заметки", "заметок"],
    project: ["проект", "проекта", "проектов"],
    member: ["участника", "участников", "участников"],
    "JS scan": ["JS-сканирование", "JS-сканирования", "JS-сканирований"],
    comment: ["комментарий", "комментария", "комментариев"],
  };
  const form = new Intl.PluralRules("ru").select(count);
  return forms[singular]?.[form === "one" ? 0 : form === "few" ? 1 : 2] ?? t(count === 1 ? singular : plural);
}

/** Activity verbs use a personal form, unlike aggregate counters ("added"). */
export function activityVerb(verb: string): string {
  if (useLangStore.getState().lang !== "ru") return verb;
  return ({ added: "добавил", reported: "зарегистрировал", started: "запустил", completed: "завершил", updated: "обновил", removed: "удалил", "status change": "изменил статус" } as Record<string, string>)[verb] ?? t(verb);
}
